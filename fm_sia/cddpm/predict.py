"""Predict from a preoperative .npy map and ordered clinical values only."""
import argparse
import json
from pathlib import Path
import numpy as np
import torch
from dataloader import center_crop
from train import build_model, resolve_device, json_save, PIPELINE_VERSION, saved_config_value
from model.fm_sia import JointFlowMatching, fixed_sia_noise


def load_checkpoint(path, device='cpu', cpu_threads=2):
    # Only load checkpoints from a trusted training run: optimizer/RNG metadata uses pickle.
    checkpoint = torch.load(path, map_location='cpu', weights_only=False)
    if checkpoint.get('pipeline_version') != PIPELINE_VERSION:
        raise ValueError('This command requires a checkpoint generated by the FM-SIA pipeline')
    args = argparse.Namespace(**checkpoint['config'])
    for key in ('sia_mode', 'lambda_scalar', 'sia_prediction'):
        if not hasattr(args, key):
            setattr(args, key, saved_config_value(checkpoint['config'], key))
    if not hasattr(args, 'reconstruction_domain'):
        args.reconstruction_domain = saved_config_value(checkpoint['config'], 'reconstruction_domain')
    target = resolve_device(device, cpu_threads)
    model = build_model(args, checkpoint['stats'])
    model.load_state_dict(checkpoint['ema'] if args.use_ema else checkpoint['model'])
    model = model.to(target).eval()
    return model, args, checkpoint['stats'], target


@torch.no_grad()
def predict_case(model, args, stats, device, pre_path, clinical_values, sample_id='case',
                 samples=None, seed=None):
    image = center_crop(np.load(pre_path, allow_pickle=False).astype(np.float32), args.image_size)
    mask = np.isfinite(image)
    if args.invalid_zero: mask &= image != 0
    if not mask.any(): raise ValueError('No valid preoperative pixels')
    normalized = (image-stats['image']['minimum'])/stats['image']['scale']
    pre = torch.from_numpy(np.where(mask, normalized, 0).astype(np.float32))[None,None].to(device)
    values = np.asarray(clinical_values, np.float32)
    if values.shape != (len(args.conditions),) or not np.isfinite(values).all():
        raise ValueError(f'Provide finite clinical values in this order: {args.conditions}')
    if stats['clinical']:
        values = (values-np.asarray(stats['clinical']['mean'],np.float32))/np.asarray(stats['clinical']['std'],np.float32)
    clinical = torch.from_numpy(values)[None].to(device)
    samples = args.eval_samples if samples is None else samples
    seed = args.eval_seed if seed is None else seed
    if samples < 1: raise ValueError('samples must be >=1')
    preds, qs, ss, raw_ss = [], [], [], []
    for m in range(samples if isinstance(model, JointFlowMatching) else 1):
        if isinstance(model, JointFlowMatching):
            out = model.sample(pre, clinical=clinical, noise=fixed_sia_noise([sample_id], seed, m, model.state_dim).to(pre))
            ss.append(out['sia'][0].item())
            if 'sia_vector' in out:
                qs.append(out['sia_vector'][0].cpu().numpy())
            else:
                raw_ss.append(out['sia_unclipped'][0].item())
            pred = out['pred']
        else:
            pred = model.sample(pre, clinical=clinical) if hasattr(model,'sample') else model(pre)['pred']
        preds.append(pred[0,0].cpu().numpy())
    raw = np.mean(preds, axis=0)*stats['image']['scale']+stats['image']['minimum']
    raw = np.where(mask, raw, np.nan)
    result = dict(sample_id=str(sample_id), model=args.model, clinical_columns=args.conditions,
                  input_map=args.input_maps, output_map=args.output_maps)
    arrays = dict(post_prediction_raw=raw, pre_valid_mask=mask)
    if ss:
        s = np.asarray(ss)
        result.update(sia_mode=model.sia_mode, sia_prediction=getattr(args, 'sia_prediction', 'flow'), pred_SIA_D=float(s.mean()),
            SIA_sample_std_D=float(s.std()), samples=samples, seed=seed,
            sample_std_is_calibrated_uncertainty=False)
        arrays.update(sia_samples=s)
        if qs:
            q = np.asarray(qs)
            result.update(pred_delta_X=float(q.mean(0)[0]), pred_delta_Y=float(q.mean(0)[1]),
                          SIA_from_mean_vector_D=float(np.linalg.norm(q.mean(0))))
            arrays['sia_vector_samples'] = q
        else:
            raw_s = np.asarray(raw_ss)
            result.update(pred_SIA_unclipped_D=float(raw_s.mean()),
                          SIA_negative_sample_fraction=float((raw_s < 0).mean()))
            arrays['sia_unclipped_samples'] = raw_s
    return result, arrays


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--checkpoint', required=True)
    p.add_argument('--pre', required=True)
    p.add_argument('--clinical', type=float, nargs='*', default=[])
    p.add_argument('--sample_id', default='case')
    p.add_argument('--samples', type=int, default=None)
    p.add_argument('--seed', type=int, default=None)
    p.add_argument('--device', default='cuda')
    p.add_argument('--output_dir', required=True)
    a=p.parse_args()
    model,args,stats,device=load_checkpoint(a.checkpoint,a.device)
    result,arrays=predict_case(model,args,stats,device,a.pre,a.clinical,a.sample_id,a.samples,a.seed)
    folder=Path(a.output_dir); folder.mkdir(parents=True,exist_ok=True)
    np.save(folder/'post_prediction_raw.npy',arrays['post_prediction_raw'])
    np.savez(folder/'prediction.npz',**arrays)
    json_save(folder/'prediction.json',result)
    print(json.dumps(result,ensure_ascii=False,indent=2))


if __name__=='__main__': main()


